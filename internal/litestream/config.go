package litestream

import (
	"errors"
	"strings"
)

// Config is the input to GenerateConfig: which database to replicate, where to,
// and whether the operator has acknowledged the no-encryption caveat for a
// remote target.
type Config struct {
	DBPath         string
	Target         Target
	AckUnencrypted bool
}

// preamble states, in the emitted file itself, what Litestream is and is not
// here: the fast-RPO complement to restic, unencrypted, sidecar-not-embedded.
// It travels with the config so an operator reading it on disk cannot mistake
// it for the authoritative DR chain.
const preamble = `# Generated by exocomp — do not edit; regenerate with ` + "`exocomp litestream config`" + `.
# Litestream ships exocomp.db's WAL frames to a replica for seconds-level RPO.
# It is the FAST-RPO COMPLEMENT to the authoritative restic DR chain, never a
# replacement: restic stays the encrypted, drill-covered chain a bare host
# recovers from. Litestream runs BESIDE exocompd as a sidecar (ADR 0012); the
# daemon generates this config and observes the replica, it does not run it.
`

// remoteWarning is emitted only for an acknowledged remote target, so the
// caveat the operator accepted is legible in the artifact they accepted it for.
const remoteWarning = `#
# WARNING: this is a REMOTE target Litestream does NOT encrypt. The operator
# acknowledged this (--ack-unencrypted): the endpoint must be an already-
# encrypted store or a trusted transport, never a plaintext bucket over the
# open internet.
`

// GenerateConfig renders a deterministic litestream.yml for one database and
// one replica target. It refuses a remote target that the operator has not
// acknowledged as unencrypted (ErrUnencryptedRemote); a local file replica
// never needs the ack. Output is byte-stable for a given input so a golden test
// pins it and a redeploy of an unchanged target is a no-op.
func GenerateConfig(c Config) (string, error) {
	if strings.TrimSpace(c.DBPath) == "" {
		return "", errors.New("litestream: empty db path")
	}
	if c.Target.Type == "" {
		return "", errors.New("litestream: unparsed replica target")
	}
	if c.Target.Remote() && !c.AckUnencrypted {
		return "", ErrUnencryptedRemote
	}

	var b strings.Builder
	b.WriteString(preamble)
	if c.Target.Remote() {
		b.WriteString(remoteWarning)
	}
	b.WriteString("dbs:\n")
	b.WriteString("  - path: " + c.DBPath + "\n")
	b.WriteString("    replicas:\n")
	writeReplica(&b, c.Target)
	return b.String(), nil
}

// writeReplica emits one replica block. Optional fields (endpoint, region, sftp
// user) are written only when set, so an AWS target and a Garage target differ
// by exactly the lines their difference warrants.
func writeReplica(b *strings.Builder, t Target) {
	b.WriteString("      - type: " + string(t.Type) + "\n")
	switch t.Type {
	case ReplicaFile:
		b.WriteString("        path: " + t.Path + "\n")
	case ReplicaS3:
		b.WriteString("        bucket: " + t.Bucket + "\n")
		if t.Path != "" {
			b.WriteString("        path: " + t.Path + "\n")
		}
		if t.Region != "" {
			b.WriteString("        region: " + t.Region + "\n")
		}
		if t.Endpoint != "" {
			b.WriteString("        endpoint: " + t.Endpoint + "\n")
		}
		b.WriteString(s3CredentialSeam)
	case ReplicaSFTP:
		b.WriteString("        host: " + t.Host + "\n")
		if t.User != "" {
			b.WriteString("        user: " + t.User + "\n")
		}
		b.WriteString("        path: " + t.Path + "\n")
		b.WriteString(sftpCredentialSeam)
	}
}

// s3CredentialSeam documents where the object-store credentials come from. They
// are injected at sidecar launch as LITESTREAM_ACCESS_KEY_ID /
// LITESTREAM_SECRET_ACCESS_KEY from the sealed secret plane, never written into
// this file — the same seam restic's s3 leg uses (disaster-recovery.md).
const s3CredentialSeam = "        # Credentials are injected at sidecar launch from the sealed secret\n" +
	"        # plane as LITESTREAM_ACCESS_KEY_ID / LITESTREAM_SECRET_ACCESS_KEY —\n" +
	"        # never written into this file.\n"

// sftpCredentialSeam points at the same seam for an SFTP key/password.
const sftpCredentialSeam = "        # The SFTP key/password is injected at sidecar launch from the\n" +
	"        # sealed secret plane (LITESTREAM_SFTP_PASSWORD or a key path) —\n" +
	"        # never written into this file.\n"
